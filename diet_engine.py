import json
import random
from pathlib import Path
from typing import List, Dict, Any, Optional

MEALS_FILE = Path(__file__).resolve().parent.parent / "data" / "meals.json"

def load_meals_dataset() -> List[Dict[str, Any]]:
    if not MEALS_FILE.exists():
        return []
    with open(MEALS_FILE, "r", encoding="utf-8") as f:
        return json.load(f)

class DietEngine:
    """
    Senior-First Rule-Based Diet Engine for ElderSOS.
    Strictly filters out allergens, disliked ingredients, and dietary violations.
    Applies nutritional heuristics tailored for elderly metabolic health.
    """
    
    STANDARD_DISCLAIMER = (
        "Medical Notice: This daily meal plan is generated by an automated nutritional rule engine for "
        "general wellness and comfort. It does NOT constitute clinical medical advice or diagnosis. "
        "Senior citizens managing chronic medical conditions must follow the personalized advice of their "
        "attending physician or a registered clinical dietician."
    )

    def __init__(self, meals_dataset: Optional[List[Dict[str, Any]]] = None):
        self.meals = meals_dataset if meals_dataset is not None else load_meals_dataset()

    ALLERGEN_KEYWORDS = {
        "dairy": ["cow milk", "dairy", "paneer", "curd", "yogurt", "ghee", "butter", "cheese"],
        "gluten": ["gluten", "wheat", "daliya", "phulka", "thepla", "flour"],
        "eggs": ["egg", "eggs", "omelette"],
        "fish": ["fish", "rohu", "pomfret", "salmon"],
        "peanuts": ["peanut", "peanuts", "groundnut"],
        "mustard": ["mustard", "sarson", "rai"],
        "soy": ["soy", "soya", "tofu"],
        "nuts": ["nuts", "almond", "walnut", "cashew"]
    }

    def filter_meals(
        self,
        diet_type: str = "veg",
        allergies: Optional[List[str]] = None,
        dislikes: Optional[List[str]] = None,
        restrictions: Optional[List[str]] = None
    ) -> List[Dict[str, Any]]:
        allergies = [a.strip().lower() for a in (allergies or []) if a.strip()]
        dislikes = [d.strip().lower() for d in (dislikes or []) if d.strip()]
        restrictions = [r.strip().lower() for r in (restrictions or []) if r.strip()]
        diet_type = (diet_type or "veg").strip().lower()

        eligible_meals = []

        for meal in self.meals:
            # 1. Diet Type Filtering
            meal_diet = meal.get("diet_type", "veg").lower()
            if diet_type == "vegan" and meal_diet != "vegan":
                continue
            if diet_type == "veg" and meal_diet not in ("veg", "vegan"):
                continue
            # For non-veg, all meals are allowed

            # 2. Strict Allergen Filtering
            meal_allergens = [a.lower() for a in meal.get("allergies", [])]
            meal_ingredients = [i.lower() for i in meal.get("ingredients", [])]
            has_allergen = False

            for allergen in allergies:
                # Direct match in tagged allergies
                if allergen in meal_allergens:
                    has_allergen = True
                    break
                
                # Check keyword synonyms
                keywords = self.ALLERGEN_KEYWORDS.get(allergen, [allergen])
                for kw in keywords:
                    if any(kw in ing for ing in meal_ingredients):
                        has_allergen = True
                        break
                if has_allergen:
                    break

            if has_allergen:
                continue

            # 3. Disliked Foods Filtering
            has_dislike = False
            meal_name_lower = meal.get("name", "").lower()
            for dislike in dislikes:
                if dislike in meal_name_lower or any(dislike in ing for ing in meal_ingredients):
                    has_dislike = True
                    break

            if has_dislike:
                continue

            # 4. Restriction Soft/Texture Requirements
            if "soft-food" in restrictions and not meal.get("soft_texture", False):
                # If senior has chewing difficulties, skip non-soft food if enough options exist
                continue

            eligible_meals.append(meal)

        return eligible_meals

    def generate_daily_plan(
        self,
        user,
        plan_date: str,
        seed: Optional[int] = None
    ) -> Dict[str, Any]:
        """
        Generates a balanced 4-meal daily plan:
        - Breakfast
        - Lunch
        - Evening Snacks
        - Dinner
        """
        if seed is not None:
            random.seed(seed)

        profile = user.diet_profile
        diet_type = profile.diet_type if profile else "veg"
        dislikes = profile.get_dislikes_list() if profile else []
        restrictions = profile.get_restrictions_list() if profile else []
        allergies = [a.name.strip().lower() for a in user.allergies]

        eligible = self.filter_meals(
            diet_type=diet_type,
            allergies=allergies,
            dislikes=dislikes,
            restrictions=restrictions
        )

        by_type = {
            "breakfast": [],
            "lunch": [],
            "evening_snacks": [],
            "dinner": []
        }

        for meal in eligible:
            mtype = meal.get("meal_type")
            if mtype in by_type:
                by_type[mtype].append(meal)

        # Fallback if strict restrictions eliminated all choices in a category
        warnings = []
        selected_meals = {}

        for mtype in ["breakfast", "lunch", "evening_snacks", "dinner"]:
            candidates = by_type[mtype]
            if not candidates:
                # Fallback to broader diet pool without dislikes/soft restriction, but KEEP allergens strict!
                broader = self.filter_meals(
                    diet_type=diet_type,
                    allergies=allergies,
                    dislikes=[],
                    restrictions=[]
                )
                broader_type = [m for m in broader if m.get("meal_type") == mtype]
                if broader_type:
                    chosen = random.choice(broader_type)
                    warnings.append(f"Limited options for {mtype.replace('_', ' ').title()}; relax dislikes for more variety.")
                else:
                    chosen = {
                        "name": f"Custom Senior {mtype.title()}",
                        "hindi_name": "संतुलित आहार",
                        "meal_type": mtype,
                        "diet_type": diet_type,
                        "ingredients": ["Prepared as per personal clinical dietician instructions"],
                        "portion_size": "Standard portion",
                        "calories": 250,
                        "protein_g": 8.0,
                        "carbs_g": 35.0,
                        "fat_g": 5.0,
                        "fiber_g": 4.0,
                        "sodium_level": "low",
                        "glycemic_index": "low",
                        "soft_texture": True,
                        "health_notes": "All allergen items strictly excluded."
                    }
                    warnings.append(f"No database meals matched all restrictions for {mtype}.")
            else:
                # Score candidates to prefer low glycemic and low sodium for seniors
                # Add random jitter to ensure different plans on 'Regenerate'
                scored = []
                for m in candidates:
                    score = 0
                    if m.get("sodium_level") == "low": score += 2
                    if m.get("glycemic_index") == "low": score += 2
                    if m.get("soft_texture"): score += 1
                    # Jitter
                    score += random.uniform(0.1, 1.5)
                    scored.append((score, m))
                scored.sort(key=lambda x: x[0], reverse=True)
                chosen = scored[0][1]

            selected_meals[mtype] = chosen

        # Calculate totals
        total_cals = sum(selected_meals[m].get("calories", 0) for m in selected_meals)
        total_protein = round(sum(selected_meals[m].get("protein_g", 0) for m in selected_meals), 1)
        total_carbs = round(sum(selected_meals[m].get("carbs_g", 0) for m in selected_meals), 1)
        total_fat = round(sum(selected_meals[m].get("fat_g", 0) for m in selected_meals), 1)
        total_fiber = round(sum(selected_meals[m].get("fiber_g", 0) for m in selected_meals), 1)

        # Condition notes handling
        condition_warning = None
        if profile and profile.conditions_note:
            condition_warning = (
                f"Health Condition Recorded ({profile.conditions_note}): Please adhere strictly to your "
                "consulting physician's clinical restrictions regarding fluid balance and glycemic targets."
            )

        return {
            "plan_date": plan_date,
            "diet_type": diet_type.upper(),
            "meals": selected_meals,
            "nutrition_totals": {
                "calories": total_cals,
                "protein_g": total_protein,
                "carbs_g": total_carbs,
                "fat_g": total_fat,
                "fiber_g": total_fiber
            },
            "warnings": warnings,
            "condition_notice": condition_warning,
            "clinician_note": profile.clinician_note if profile else None,
            "medical_disclaimer": self.STANDARD_DISCLAIMER
        }
